package com.dzaitsev.rxviper.plugin

import java.util.Locale

internal data class InteractorSpec(val name: String, val requestType: String, val responseType: String)

internal data class ScreenSpec(
    val name: String,
    val includeRouter: Boolean,
    val includeInteractor: Boolean,
    val routesTo: List<String>,
    val interactors: List<InteractorSpec>,
)

/** Pure source generation: no Gradle, reflection, runtime backend or codegen library required. */
internal object KotlinGenerator {
    private val identifier = Regex("[A-Za-z_][A-Za-z0-9_]*")
    private val keywords = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
        "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
        "typeof", "val", "var", "when", "while", "_",
    )

    fun generate(packageName: String, backend: Backend, screens: List<ScreenSpec>): Map<String, String> {
        qualifiedName(packageName)
        val sources = sortedMapOf<String, String>()
        fun add(pkg: String, name: String, body: String) {
            val path = "${pkg.replace('.', '/')}/$name.kt"
            require(path !in sources) { "Duplicate generated type: $pkg.$name" }
            sources[path] = "// Generated by RxViper. Copy into src/main/kotlin before editing.\npackage $pkg\n\n$body\n"
        }
        screens.forEach { screen ->
            name(screen.name)
            val prefix = screen.name.replaceFirstChar { it.uppercaseChar() }
            val pkg = "$packageName.${screen.name.lowercase(Locale.ROOT)}"
            qualifiedName(pkg)
            val cases = if (screen.includeInteractor) {
                screen.interactors.ifEmpty { listOf(InteractorSpec(screen.name, "kotlin.Unit", "kotlin.Any")) }
            } else {
                emptyList()
            }
            cases.forEach {
                name(it.name)
                qualifiedName(it.requestType)
                qualifiedName(it.responseType)
            }
            val resultCallbacks = cases.joinToString("\n") {
                "    fun show${it.name.replaceFirstChar { char -> char.uppercaseChar() }}(result: ${it.responseType})"
            }
            add(pkg, "${prefix}ViewCallbacks", "interface ${prefix}ViewCallbacks : com.dzaitsev.rxviper.ViewCallbacks {\n" +
                "$resultCallbacks\n    fun showError(error: Throwable)\n}")
            if (screen.includeRouter) {
                val routes = screen.routesTo.map { route ->
                    name(route)
                    "    fun navigateTo${route.replaceFirstChar { it.uppercaseChar() }}()"
                }
                require(routes.distinct().size == routes.size) { "Duplicate routes in ${screen.name}" }
                add(pkg, "${prefix}Router", "interface ${prefix}Router : com.dzaitsev.rxviper.Router {\n${routes.joinToString("\n")}\n}")
            }
            val parent = if (screen.includeRouter) {
                "com.dzaitsev.rxviper.ViperPresenter<${prefix}ViewCallbacks, ${prefix}Router>(\n" +
                    "    ${prefix}ViewCallbacks::class.java, ${prefix}Router::class.java,\n)"
            } else {
                "com.dzaitsev.rxviper.Presenter<${prefix}ViewCallbacks>(${prefix}ViewCallbacks::class.java)"
            }
            add(pkg, "${prefix}Presenter", presenter(prefix, parent, cases, backend))
            if (screen.includeInteractor) {
                cases.forEach { spec ->
                    val interactorName = "${spec.name.replaceFirstChar { it.uppercaseChar() }}Interactor"
                    add(pkg, interactorName, interactor(interactorName, spec, backend))
                }
            }
        }
        return sources
    }

    private fun presenter(prefix: String, parent: String, cases: List<InteractorSpec>, backend: Backend): String {
        if (cases.isEmpty()) return "class ${prefix}Presenter : $parent"
        val coroutine = backend == Backend.COROUTINES
        fun title(spec: InteractorSpec) = spec.name.replaceFirstChar { it.uppercaseChar() }
        fun field(spec: InteractorSpec) = "${spec.name.replaceFirstChar { it.lowercaseChar() }}Interactor"
        val constructor = buildList {
            if (coroutine) add("    private val scope: kotlinx.coroutines.CoroutineScope,")
            cases.forEach {
                val type = if (coroutine) {
                    "com.dzaitsev.rxviper.SuspendInteractor<${it.requestType}, ${it.responseType}>"
                } else {
                    "${title(it)}Interactor"
                }
                add("    private val ${field(it)}: $type,")
            }
        }.joinToString("\n")
        val methods = cases.joinToString("\n\n") { spec ->
            val default = if (spec.requestType == "kotlin.Unit") " = Unit" else ""
            val execution = if (coroutine) {
                "jobs.removeAll { it.isCompleted }\n        jobs.add(${field(spec)}.execute(scope, request,\n" +
                    "            onSuccess = { view.show${title(spec)}(it) },\n" +
                    "            onError = { view.showError(it) },\n        ))"
            } else {
                "${field(spec)}.execute(request,\n" +
                    "            onNext = { view.show${title(spec)}(it) },\n" +
                    "            onError = { view.showError(it) },\n        )"
            }
            "    fun do${title(spec)}(request: ${spec.requestType}$default) {\n        $execution\n    }"
        }
        val state = if (coroutine) "    private val jobs = mutableListOf<kotlinx.coroutines.Job>()\n\n" else ""
        val cleanup = if (coroutine) "        jobs.forEach { it.cancel() }\n        jobs.clear()" else {
            cases.joinToString("\n") { "        ${field(it)}.clear()" }
        }
        val extensionPackage = if (coroutine) "coroutines" else backend.name.lowercase(Locale.ROOT)
        return "import com.dzaitsev.rxviper.$extensionPackage.execute\n\n" +
            "class ${prefix}Presenter(\n$constructor\n) : $parent {\n$state$methods\n\n" +
            "    override fun onDropView(view: ${prefix}ViewCallbacks) {\n$cleanup\n    }\n}"
    }

    private fun interactor(name: String, spec: InteractorSpec, backend: Backend): String {
        val types = "<${spec.requestType}, ${spec.responseType}>"
        if (backend == Backend.COROUTINES) {
            return """
                |class $name(dispatcher: kotlinx.coroutines.CoroutineDispatcher) :
                |    com.dzaitsev.rxviper.coroutines.SuspendInteractor$types(dispatcher) {
                |    override suspend fun run(request: ${spec.requestType}): ${spec.responseType} =
                |        TODO("Implement this interactor")
                |}
            """.trimMargin()
        }
        val rx = when (backend) {
            Backend.RXJAVA -> "rx"
            Backend.RXJAVA2 -> "io.reactivex"
            Backend.RXJAVA3 -> "io.reactivex.rxjava3.core"
            Backend.COROUTINES -> error("Already handled")
        }
        val module = backend.name.lowercase(Locale.ROOT)
        val stream = if (backend == Backend.RXJAVA) "Observable" else "Flowable"
        return """
            |class $name(
            |    subscribeScheduler: $rx.Scheduler,
            |    observeScheduler: $rx.Scheduler,
            |) : com.dzaitsev.rxviper.$module.Interactor$types(subscribeScheduler, observeScheduler) {
            |    override fun create$stream(request: ${spec.requestType}): $rx.$stream<${spec.responseType}> =
            |        $rx.$stream.empty() // Replace with this interactor's data source.
            |}
        """.trimMargin()
    }

    private fun name(value: String) {
        require(identifier.matches(value) && value !in keywords) { "Invalid Kotlin identifier: $value" }
    }

    private fun qualifiedName(value: String) {
        require(value.isNotBlank()) { "A package or type name cannot be empty" }
        value.split('.').forEach(::name)
    }
}
